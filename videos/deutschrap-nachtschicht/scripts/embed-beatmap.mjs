// Writes beatmap.json into beatmap.js so the composition can read the beat grid
// without a render-time fetch.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url);
const map = JSON.parse(readFileSync(new URL("beatmap.json", root), "utf8"));
const { kicks, snares, rolls, impacts, bar_sec, bpm } = map;
writeFileSync(
  new URL("beatmap.js", root),
  `// Generated by scripts/embed-beatmap.mjs from beatmap.json. Do not edit.\nwindow.NACHTSCHICHT_BEATMAP = ${JSON.stringify({ bpm, bar_sec, kicks, snares, rolls, impacts })};\n`,
);
